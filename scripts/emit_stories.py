def main() -> None:
    countries = json.loads((ROOT / "data" / "countries.json").read_text())["countries"]
    isos = [country["iso2"] for country in countries]
    missing = [iso for iso in isos if iso not in DETAIL and iso not in SHORT]
    extra = sorted((set(DETAIL) | set(SHORT)) - set(isos))
    overlap = sorted(set(DETAIL) & set(SHORT))
    if missing or extra or overlap:
        raise SystemExit(f"missing={missing} extra={extra} overlap={overlap}")
    out = {}
    for iso in isos:
        if iso in DETAIL:
            origin, became, history, anecdote = DETAIL[iso]
            out[iso] = {
                "level": "detail",
                "origin": origin,
                "became": became,
                "history": history,
                "anecdote": anecdote,
                "note": "",
            }
        else:
            out[iso] = {
                "level": "short",
                "origin": "",
                "became": "",
                "history": "",
                "anecdote": "",
                "note": SHORT[iso],
            }
    (ROOT / "data" / "stories.json").write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"stories {len(out)} detail {len(DETAIL)} short {len(SHORT)}")


if __name__ == "__main__":
    main()
